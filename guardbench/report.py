"""`guardbench report`: write docs/RESULTS.md from the baselines. Deterministic: no clock, no randomness
beyond fixed seeds, so the same data gives the same file."""
import os
import sys

from . import reviewers as R
from .analysis import TARGET
from .baselines import flag_every_hunk, make_random, random_hit_probability
from .defects import CLASSES, manifest_hash
from .patch import anchors
from .scoring import newcombe_diff, run

BANNER = """\
> **No hypothesis (H1, H2, H3) has a verdict.** Every number below comes from trivial baselines
> (and one labelled toy script), not from a model or a real code reviewer, and none was run on any
> model. This is not evidence about any model. Baselines and toys remain descriptive regardless of sample size.
> The dev split is public. Real reviewer runs are future work.
"""


def _size_note(heldout):
    if not heldout:
        return ("> Held-out count is unavailable in this run. The prospective reporting minimum "
                "is %d defects (the original size target); any smaller reviewer run is a **pilot**. Size alone never establishes "
                "eligibility. See `prereg/AMENDMENT-4.md`.\n" % TARGET)
    count = len(heldout)
    status = ("below the prospective reporting minimum (%d), so such a reviewer run is a **pilot**" % TARGET
              if count < TARGET else
              "meets the prospective size minimum only (%d); size alone does not establish eligibility" % TARGET)
    return "> Held-out count in this run: **%d pairs**; %s. See `prereg/AMENDMENT-4.md`.\n" % (count, status)


def _f(r):
    lo, hi = r["ci"]
    return "n/a" if r["recall"] is None else "%.3f [%.3f, %.3f] (%d/%d)" % (r["recall"], lo, hi, r["found"], r["n"])


def _alarm(a):
    return "%.3f [%.3f, %.3f] (%d/%d)" % (a["rate"], a["ci"][0], a["ci"][1], a["alarms"], a["n"])


def _diff(k1, n1, k2, n2):
    if not n1 or not n2:
        return "n/a"
    d, lo, hi = newcombe_diff(k1, n1, k2, n2)
    return "%+.3f [%+.3f, %+.3f]" % (d, lo, hi)


def _toy():
    return R.command_reviewer([sys.executable, os.path.join(os.path.dirname(os.path.dirname(
        os.path.abspath(__file__))), "examples", "toy_reviewer.py")], timeout=60)


def _row(cells):
    return "| " + " | ".join(cells) + " |"


def _split(title, defects, revs):
    out = ["## " + title, ""]
    counts = {c: sum(d.cls == c for d in defects) for c in CLASSES}
    hunks = [len(anchors(d.bug_patch)) for d in defects]
    out.append("%d pairs over %d apps; per class: %s; hunks per bug diff: min %d, mean %.1f, max %d." % (
        len(defects), len({d.app for d in defects}), ", ".join("%s %d" % (c, n) for c, n in counts.items()),
        min(hunks), sum(hunks) / len(hunks), max(hunks)))
    p = [random_hit_probability(d.bug_patch, d.file, d.start, d.end) for d in defects]
    out += ["", "Exact expected recall of `random` (mean per-diff hit probability): **%.3f**." % (sum(p) / len(p)), ""]
    sums = {label: run(defects, fn) for label, fn in revs}
    out += [_row(["Reviewer", "Recall", "Guard recall", "Logic recall", "Clean-twin alarm rate", "Precision (point only)", "F1 (point only)"]),
            _row(["---"] * 7)]
    for label, s in sums.items():
        g, lg = s["per_group"].get("guard"), s["per_group"].get("logic")
        out.append(_row([label, _f(s["overall"]), _f(g) if g else "n/a", _f(lg) if lg else "n/a",
                         _alarm(s["clean_alarm"]), "n/a" if s["precision"] is None else "%.3f" % s["precision"],
                         "%.3f" % s["f1"]]))
    out += ["", "Per-class recall (Wilson 95%):", "", _row(["Reviewer"] + list(CLASSES)), _row(["---"] * (1 + len(CLASSES)))]
    for label, s in sums.items():
        out.append(_row([label] + [_f(s["per_class"][c]) if c in s["per_class"] else "n/a" for c in CLASSES]))
    out.append("")
    return out, sums


def build(dev, heldout, toy=True, split_hash=None, manifest=None):
    """Return the markdown text. `heldout` is a list of defects or None; `manifest` its manifest hash."""
    revs = [("random (seed 0, one run)", make_random(0)), ("hunk-all", flag_every_hunk)]
    if toy:
        revs.append(("toy `examples/toy_reviewer.py` (a toy, not a tool)", _toy()))
    lines = ["# GuardBench results (baselines only)", "",
             "Generated by `python -m guardbench report`; do not edit by hand.", "", BANNER,
             _size_note(heldout)]
    sec, dev_sums = _split("Dev split (public)", dev, revs)
    lines += sec
    held_sums = None
    if heldout:
        sec, held_sums = _split("Held-out split (private items; numbers only)", heldout, revs)
        lines += sec
        if manifest:
            ok = split_hash is not None and manifest == split_hash
            lines += ["Held-out manifest hash `%s`: %s `prereg/split.sha256`." % (
                manifest, "matches" if ok else "**MISMATCH with**"), ""]
    else:
        lines += ["## Held-out split", "", "Not available in this run (`GUARDBENCH_HELDOUT` unset); "
                  "run `report` with the private repo to include it.", ""]
    lines += ["## Differences (Newcombe hybrid-score 95% intervals)", "",
              "These are descriptive baseline differences, not hypothesis verdicts. H1 and H3 are about "
              "a reviewer under test, and none was tested. A negative guard-minus-logic value means the "
              "baseline found fewer guard than logic defects; a positive dev-minus-held-out value means "
              "dev is easier for that baseline.", "",
              _row(["Reviewer", "Guard minus logic (dev)"] + (["Guard minus logic (held-out)", "Dev minus held-out (overall)"]
                                                               if held_sums else [])),
              _row(["---"] * (4 if held_sums else 2))]
    for label in dev_sums:
        gl = lambda s: _diff(s["per_group"]["guard"]["found"], s["per_group"]["guard"]["n"],
                             s["per_group"]["logic"]["found"], s["per_group"]["logic"]["n"]) \
            if "guard" in s["per_group"] and "logic" in s["per_group"] else "n/a"
        cells = [label, gl(dev_sums[label])]
        if held_sums:
            d, h = dev_sums[label]["overall"], held_sums[label]["overall"]
            cells += [gl(held_sums[label]), _diff(d["found"], d["n"], h["found"], h["n"])]
        lines.append(_row(cells))
    lines += ["", "## How to read this", "",
              "- `hunk-all` finds every defect by construction (recall 1.000) and alarms on every clean twin; "
              "only precision, F1 and the alarm rate separate it from a useful reviewer.",
              "- `random` shows the localisation floor: with 8 or more hunks it rarely lands on the defect.",
              "- The toy script is a 40-line heuristic that looks for removed guard keywords. How much it "
              "finds measures how much of the benchmark is solvable by planted-bug style artifacts "
              "(a deleted `raise`, `return False` flipped to `return True`), not reviewing skill.",
              "- Recall and clean-twin alarm-rate intervals are Wilson 95%; difference intervals use "
              "the Newcombe hybrid-score method. Precision and F1 are descriptive point estimates only; "
              "no precision or F1 interval is supplied. F1 is not a binomial proportion.",
              "- Small splits and smaller per-class cells have wide intervals. Items sharing an app "
              "may be dependent; the printed intervals do not adjust for app clustering.",
              "- Limits: synthetic defects written by one AI agent, cosmetic generated noise, public READMEs "
              "and tests that hint at each rule, held-out noise that is reproducible from public tools. "
              "See the README, `prereg/AMENDMENTS.md` and `prereg/AMENDMENT-4.md`.", ""]
    return "\n".join(lines)
